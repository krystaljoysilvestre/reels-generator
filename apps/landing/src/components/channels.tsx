function ChannelTile({ tile, index }: { tile: Tile; index: number }) {
  const videoRef = useRef<HTMLVideoElement>(null)

  const play = () => {
    if (window.matchMedia('(prefers-reduced-motion: reduce)').matches) return
    void videoRef.current?.play().catch(() => {})
  }
  const stop = () => {
    const v = videoRef.current
    if (!v) return
    v.pause()
    v.currentTime = 0
  }

  return (
    <figure
      className="kx-tile group relative m-0 aspect-[9/14] overflow-hidden rounded-[18px] border border-white/[0.12] bg-night"
      onMouseEnter={play}
      onMouseLeave={stop}
      onFocus={play}
      onBlur={stop}
      tabIndex={0}
    >
      <Image
        src={tile.image}
        alt={tile.alt}
        fill
        sizes="(min-width: 1024px) 25vw, 50vw"
        className="object-cover"
      />
      {/* the living take — fades in over the still on hover */}
      <video
        ref={videoRef}
        src={tile.video}
        muted
        loop
        playsInline
        preload="metadata"
        aria-hidden
        className="absolute inset-0 h-full w-full object-cover opacity-0 transition-opacity duration-300 group-hover:opacity-100 group-focus:opacity-100 motion-reduce:hidden"
      />
      {/* scrim so name/tag stay legible on bright frames */}
      <div className="pointer-events-none absolute inset-0 bg-[linear-gradient(180deg,rgba(0,0,0,0.22),transparent_30%,transparent_55%,rgba(0,0,0,0.72))]" />
      <div className="absolute left-3 top-3 inline-flex items-center gap-[5px] rounded-[20px] border border-white/[0.22] bg-black/40 px-[9px] py-1 backdrop-blur-[6px]">
        <span className="relative inline-flex h-1.5 w-1.5">
          <span
            className="kx-blink absolute inset-0 rounded-full"
            style={{ background: tile.dot, animationDelay: `${-0.4 * index}s` }}
          />
        </span>
        <span className="mono text-[9px] font-700 tracking-[0.1em] text-white">{tile.badge}</span>
      </div>
      <div className="absolute inset-x-3.5 bottom-3.5">
        <div className="font-display text-base font-800">{tile.name}</div>
        <div className="mono mt-0.5 text-[10px] text-white/80">{tile.tag}</div>
      </div>
    </figure>
  )
}

